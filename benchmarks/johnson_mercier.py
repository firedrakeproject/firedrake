#!/usr/bin/env python
"""Measure simplex Johnson--Mercier code generation."""

import argparse
import hashlib

import numpy

from finat.ufl import FiniteElement, VectorElement
from tsfc import compile_form
from ufl import FunctionSpace, Mesh, TestFunction, TrialFunction, div, dx, inner
from ufl.cell import Cell


def compile_target(dim: int) -> object:
    """Compile the JM mass-plus-divergence target on a simplex.

    Parameters
    ----------
    dim
        Topological dimension.

    Returns
    -------
    object
        Compiled TSFC kernel.
    """
    cell = Cell(("triangle", "tetrahedron")[dim - 2])
    mesh = Mesh(VectorElement("CG", cell, 1))
    element = FiniteElement("Johnson-Mercier", cell, 1)
    space = FunctionSpace(mesh, element)
    u = TrialFunction(space)
    v = TestFunction(space)
    form = (inner(u, v) + inner(div(u), div(v))) * dx
    return compile_form(form, parameters={"mode": "spectral"})[0]


def temporary_metrics(kernel: object) -> tuple[int, int, int, int]:
    """Measure statically allocated Loopy temporaries.

    Parameters
    ----------
    kernel
        Compiled TSFC kernel.

    Returns
    -------
    scalar_count
        Number of scalar temporaries.
    array_count
        Number of array temporaries.
    array_elements
        Total entries in array temporaries.
    largest_array
        Entries in the largest array temporary.
    """
    temporaries = kernel.ast.default_entrypoint.temporary_variables.values()
    shapes = [temporary.shape for temporary in temporaries]
    sizes = [numpy.prod(shape, dtype=int) for shape in shapes if shape]
    return (
        sum(not shape for shape in shapes),
        len(sizes),
        sum(sizes),
        max(sizes, default=0),
    )


def main() -> None:
    """Print compiler metrics as copyable Markdown."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--dims", nargs="+", type=int, default=(2, 3))
    args = parser.parse_args()
    print("<!-- generated by benchmarks/johnson_mercier.py -->")
    print("| dim | flops | scalar temps | array temps | elements | bytes | largest | AST lines | hash |")
    print("| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |")
    for dim in args.dims:
        kernel = compile_target(dim)
        source = str(kernel.ast)
        digest = hashlib.sha256(source.encode()).hexdigest()[:12]
        nscalar, narray, nelem, largest = temporary_metrics(kernel)
        print(f"| {dim} | {kernel.flop_count:.0f} | "
              f"{nscalar} | {narray} | {nelem} | {8 * nelem} | {largest} | "
              f"{len(source.splitlines())} | {digest} |")


if __name__ == "__main__":
    main()
